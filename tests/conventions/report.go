package conventions

import (
	"fmt"
	"sort"
	"strings"
)

type RepoResult struct {
	Repo     string    `json:"repo"`
	Findings []Finding `json:"findings"`
	Error    string    `json:"error,omitempty"`
}

// RulesMarkdown renders the catalogue as lint/CONVENTIONS.md.
func RulesMarkdown() string {
	var b strings.Builder
	b.WriteString("<!-- generated by: cd tests && go run ./cmd/wamlint -rules > ../lint/CONVENTIONS.md; do not edit -->\n")
	b.WriteString("# WAM convention checks\n\n")
	fmt.Fprintf(&b, "These checks run in the `conventions` job of `.github/workflows/linting.yml` on every module PR. Each check enforces a rule of the [WAM standard](%s).\n\n", StandardURL)
	b.WriteString("| ID | Rule | Severity | Check |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, rule := range Rules() {
		if rule.ID == "WAM000" {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n",
			markdownCell(rule.ID), markdownCell(rule.Standard),
			markdownCell(string(rule.Severity)), markdownCell(rule.Title))
	}
	b.WriteString("\n## Ignoring a finding\n\n")
	b.WriteString("Put `# wam-lint-ignore WAM002 <reason>` on the line of the finding or on the line above it. Several IDs can be separated by commas. The reason is mandatory; an ignore without a reason or with an unknown ID is reported as WAM000.\n")
	b.WriteString("\n## Warning and enforce mode\n\n")
	b.WriteString("Repos listed in `lint/conventions-enforced.txt` fail on error findings. All other repos get the findings as warnings only.\n")
	return b.String()
}

// BaselineMarkdown summarises findings across many repos.
func BaselineMarkdown(results []RepoResult) string {
	type ruleStats struct {
		id       string
		title    string
		severity Severity
		count    int
		repos    map[string]struct{}
	}
	type repoStats struct {
		repo     string
		errors   int
		warnings int
		counts   map[string]int
	}

	byRule := map[string]*ruleStats{}
	var repos []repoStats
	var clean []string
	var toolErrors []RepoResult
	withErrors := 0

	for _, result := range results {
		if result.Error != "" {
			toolErrors = append(toolErrors, result)
		}
		if len(result.Findings) == 0 {
			if result.Error == "" {
				clean = append(clean, result.Repo)
			}
			continue
		}

		rs := repoStats{repo: result.Repo, counts: map[string]int{}}
		for _, finding := range result.Findings {
			if finding.Severity == SeverityError {
				rs.errors++
			} else {
				rs.warnings++
			}
			rs.counts[finding.RuleID]++

			stats := byRule[finding.RuleID]
			if stats == nil {
				rule, _ := RuleByID(finding.RuleID)
				stats = &ruleStats{id: finding.RuleID, title: rule.Title, severity: finding.Severity, repos: map[string]struct{}{}}
				byRule[finding.RuleID] = stats
			}
			stats.count++
			stats.repos[result.Repo] = struct{}{}
		}
		if rs.errors > 0 {
			withErrors++
		}
		repos = append(repos, rs)
	}

	rules := make([]*ruleStats, 0, len(byRule))
	for _, stats := range byRule {
		rules = append(rules, stats)
	}
	sort.Slice(rules, func(i, j int) bool {
		if len(rules[i].repos) != len(rules[j].repos) {
			return len(rules[i].repos) > len(rules[j].repos)
		}
		return rules[i].id < rules[j].id
	})
	sort.Slice(repos, func(i, j int) bool {
		ni, nj := repos[i].errors+repos[i].warnings, repos[j].errors+repos[j].warnings
		if ni != nj {
			return ni > nj
		}
		return repos[i].repo < repos[j].repo
	})
	sort.Strings(clean)
	sort.Slice(toolErrors, func(i, j int) bool { return toolErrors[i].Repo < toolErrors[j].Repo })

	var b strings.Builder
	b.WriteString("# WAM conventions baseline\n\n")
	fmt.Fprintf(&b, "Repositories: %d\n", len(results))
	fmt.Fprintf(&b, "Clean repositories: %d\n", len(clean))
	fmt.Fprintf(&b, "Repositories with error findings: %d\n", withErrors)

	b.WriteString("\n## Findings per rule\n\n")
	b.WriteString("| ID | Check | Severity | Findings | Repos affected |\n")
	b.WriteString("| --- | --- | --- | ---: | ---: |\n")
	for _, stats := range rules {
		fmt.Fprintf(&b, "| %s | %s | %s | %d | %d |\n",
			markdownCell(stats.id), markdownCell(stats.title),
			markdownCell(string(stats.severity)), stats.count, len(stats.repos))
	}

	b.WriteString("\n## Findings per repo\n\n")
	b.WriteString("| Repo | Errors | Warnings | Top rules |\n")
	b.WriteString("| --- | ---: | ---: | --- |\n")
	for _, stats := range repos {
		ids := make([]string, 0, len(stats.counts))
		for id := range stats.counts {
			ids = append(ids, id)
		}
		sort.Slice(ids, func(i, j int) bool {
			if stats.counts[ids[i]] != stats.counts[ids[j]] {
				return stats.counts[ids[i]] > stats.counts[ids[j]]
			}
			return ids[i] < ids[j]
		})
		if len(ids) > 3 {
			ids = ids[:3]
		}
		top := make([]string, 0, len(ids))
		for _, id := range ids {
			top = append(top, fmt.Sprintf("%s (%d)", id, stats.counts[id]))
		}
		fmt.Fprintf(&b, "| %s | %d | %d | %s |\n",
			markdownCell(stats.repo), stats.errors, stats.warnings, strings.Join(top, ", "))
	}

	b.WriteString("\n## Clean repos\n\n")
	if len(clean) == 0 {
		b.WriteString("None.\n")
	} else {
		b.WriteString(strings.Join(clean, ", ") + "\n")
	}

	b.WriteString("\n## Tool errors\n\n")
	if len(toolErrors) == 0 {
		b.WriteString("None.\n")
	} else {
		for _, item := range toolErrors {
			fmt.Fprintf(&b, "- %s — %s\n", item.Repo, markdownCell(item.Error))
		}
	}
	return b.String()
}

func markdownCell(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}
